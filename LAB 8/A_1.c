// 1. Print 1 to 10 using while loop

#include <stdio.h>

int main()
{
    // Start counting from 1
    int i = 1;

    // Repeat while i is less than or equal to 10
    while(i <= 10)
    {
        // Display the current number
        printf("%d ", i);

        // Increase i by 1
        i++;
    }

    return 0;
}